CREATE OR REPLACE FUNCTION post_category_rules() RETURNS trigger AS $$
DECLARE
  needs_condition boolean;
BEGIN
  SELECT requires_condition INTO needs_condition FROM category WHERE id = NEW.category_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'unknown category %', NEW.category_id USING ERRCODE = 'check_violation';
  END IF;
  IF needs_condition AND NEW.condition IS NULL THEN
    RAISE EXCEPTION 'category % needs a condition', NEW.category_id USING ERRCODE = 'check_violation';
  END IF;
  IF NOT needs_condition AND NEW.condition IS NOT NULL THEN
    RAISE EXCEPTION 'category % takes no condition', NEW.category_id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
